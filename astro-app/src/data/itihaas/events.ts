export const getEventsByEra = (eraId: string): HistoricalEvent[] => {
  return HISTORICAL_EVENTS.filter((e) => e.era === eraId);
};

export const getEventById = (id: string): HistoricalEvent | undefined => {
  return HISTORICAL_EVENTS.find((e) => e.id === id);
};

export const getAllKeyFigures = (): string[] => {
  const figureMap = new Map<string, number>();
  HISTORICAL_EVENTS.forEach((e) => {
    e.keyFigures.forEach((fig) => {
      figureMap.set(fig, (figureMap.get(fig) || 0) + 1);
    });
  });
  return Array.from(figureMap.entries())
    .sort((a, b) => b[1] - a[1])
    .map(([figure]) => figure);
};

export const getEventsByFigure = (figure: string): HistoricalEvent[] => {
  const normalized = figure.trim().toLowerCase();
  return HISTORICAL_EVENTS.filter((e) =>
    e.keyFigures.some((f) => f.toLowerCase() === normalized)
  );
};
